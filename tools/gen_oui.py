def main(path):
    rx = [(n, re.compile(p)) for n, p in VENDORS]
    names = []; entries = {}
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        if not line or line.startswith("#"): continue
        parts = line.split("\t")
        if len(parts) < 3: continue
        pre, long = parts[0].strip(), parts[2].strip()
        if not re.fullmatch(r"[0-9A-Fa-f]{2}:[0-9A-Fa-f]{2}:[0-9A-Fa-f]{2}", pre): continue
        for n, r in rx:
            if r.search(long):
                if n not in names: names.append(n)
                entries[int(pre.replace(":", ""), 16)] = names.index(n); break
    keys = sorted(entries)
    assert len(names) < 256
    out = ["// AUTO-GENERATED by tools/gen_oui.py from Wireshark's manuf (IEEE registry data). Do not edit.",
           "#pragma once", "#include <stdint.h>", "#include <pgmspace.h>",
           f"static const char *const OUI_VENDORS[{len(names)}] = {{" + ",".join(f'"{n}"' for n in names) + "};",
           f"static const uint16_t OUI_COUNT = {len(keys)};",
           "static const uint32_t OUI_TABLE[] PROGMEM = {"]
    row = []
    for k in keys:
        row.append(f"0x{(k << 8) | entries[k]:08x}")
        if len(row) == 8: out.append("  " + ",".join(row) + ","); row = []
    if row: out.append("  " + ",".join(row) + ",")
    out.append("};")
    Path(__file__).resolve().parent.parent.joinpath("src/esp_radar/oui_table.h").write_text("\n".join(out) + "\n")
    print(f"{len(keys)} OUIs, {len(names)} vendors, {len(keys)*4} bytes")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "manuf.txt")
