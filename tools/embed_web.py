#!/usr/bin/env python3
"""Embed web/radar.html and web/setup.html into src/esp_radar/web_ui.h (PROGMEM raw strings)."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
out = ["// AUTO-GENERATED by tools/embed_web.py from web/*.html - do not edit by hand", "#pragma once", "#include <pgmspace.h>", ""]
for name, var in (("radar.html", "RADAR_HTML"), ("setup.html", "SETUP_HTML")):
    html = (root / "web" / name).read_text(encoding="utf-8")
    assert ')=====' not in html
    out.append(f'static const char {var}[] PROGMEM = R"=====({html})=====";')
    out.append("")
(root / "src" / "esp_radar" / "web_ui.h").write_text("\n".join(out), encoding="utf-8")
print("wrote web_ui.h")
