#!/usr/bin/env python3
"""Gzip web/index.html and web/setup.html into src/esp_radar/web_assets.h (served with Content-Encoding: gzip)."""
import gzip
from pathlib import Path
root = Path(__file__).resolve().parent.parent
out = ["// AUTO-GENERATED by tools/embed_web.py from web/*.html - do not edit by hand", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
for name, var in (("index.html", "INDEX_HTML_GZ"), ("setup.html", "SETUP_HTML_GZ")):
    raw = (root / "web" / name).read_bytes()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    out.append(f"// {name}: {len(raw)} bytes -> {len(gz)} bytes gzip")
    out.append(f"static const size_t {var}_LEN = {len(gz)};")
    out.append(f"static const uint8_t {var}[] = {{")
    for i in range(0, len(gz), 20):
        out.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    out.append("};")
    out.append("")
    print(f"{name}: {len(raw)} -> {len(gz)} gz")
(root / "src" / "esp_radar" / "web_assets.h").write_text("\n".join(out), encoding="utf-8")
